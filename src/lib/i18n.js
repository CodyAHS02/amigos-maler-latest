export function translateMessage(value, locale) {
  const keys = [...new Set(Object.values(messages).flatMap((catalog) => Object.keys(catalog)))];
  const normalize = (text) => text.replace(/\s+/g, " ").trim().toLowerCase();
  const normalizedValue = normalize(value);
  const findSource = (text) => keys.find((key) =>
    normalize(key) === normalize(text) || Object.values(messages).some((catalog) => catalog[key] && normalize(catalog[key]) === normalize(text))
  );
  const source = findSource(value) || value;
  if (source === value && normalizedValue.includes(" · ")) {
    return value.trim().split(/\s+·\s+/).map((part) => {
      const partSource = findSource(part);
      return messages[locale]?.[partSource] || part;
    }).join(" · ");
  }
  return messages[locale]?.[source] || source;
}
